/** Gölge kökler dahil verilen noktadaki en derin öğe. */
export function deepElementFromPoint(x: number, y: number): Element | null {
  let el = document.elementFromPoint(x, y);
  while (el?.shadowRoot) {
    const inner = el.shadowRoot.elementFromPoint(x, y);
    if (!inner || inner === el) break;
    el = inner;
  }
  return el;
}

/** Olayın gerçek hedefi (gölge DOM içinden). */
export function eventTarget(e: Event): EventTarget | null {
  return (e.composedPath?.()[0] as EventTarget | undefined) ?? e.target;
}

export function isEditable(target: EventTarget | null): target is HTMLElement {
  if (!(target instanceof HTMLElement)) return false;
  if (target.isContentEditable) return true;
  if (target instanceof HTMLTextAreaElement) return !target.readOnly && !target.disabled;
  if (target instanceof HTMLInputElement) {
    const type = (target.type || 'text').toLowerCase();
    return ['text', 'search', ''].includes(type) && !target.readOnly && !target.disabled;
  }
  return false;
}
