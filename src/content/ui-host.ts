/** Sayfa stillerinden yalıtılmış (gölge DOM) arayüz kapsayıcısı oluşturur. */
export function createUiHost(name: string, css: string): { host: HTMLElement; root: ShadowRoot } {
  const host = document.createElement('div');
  host.setAttribute('data-bp-ui', name);
  host.style.cssText = 'all: initial; position: static;';
  const root = host.attachShadow({ mode: 'open' });
  const style = document.createElement('style');
  style.textContent = BASE_CSS + css;
  root.appendChild(style);
  (document.documentElement ?? document.body).appendChild(host);
  return { host, root };
}

